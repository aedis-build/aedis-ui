import { parseThemeJson, themeToCss } from "../../../apps/www/registry/aedis/lib/custom-theme";

/**
 * `aedis theme import`: the same typed validation as the browser (#41) before anything is written. Returns the CSS
 * for the app to import after the Aedis theme, or every reason the theme was refused.
 */
export function themeImport(json: string, source: string): { ok: true; css: string; name: string } | { ok: false; errors: string[] } {
  const result = parseThemeJson(json);
  if (!result.ok) return result;
  const name = result.theme.name.replace(/\*\//g, "");
  return { ok: true, name, css: `/* Generated by aedis theme import from ${source.replace(/\*\//g, "")} (${name}). Do not edit; import again. */\n${themeToCss(result.theme)}\n` };
}
